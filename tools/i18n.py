"""Textos de la interfaz (inglés + español) para un proyecto de Nexus Island.

Cada proyecto tiene:
  Properties/Strings.resx      inglés (idioma de respaldo)
  Properties/Strings.es.resx   español
  Properties/Strings.cs        clase de acceso GENERADA por este script (no editar a mano)

Uso:
  python tools/i18n.py spec.json [--dry]     aplica una migración / agrega textos (ver formato abajo)
  python tools/i18n.py --regen <proyecto>    solo regenera Strings.cs desde el .resx (tras editarlo a mano)

spec.json = {
  "root": "src/Proyecto",                  # carpeta del proyecto
  "namespace": "Proyecto.Properties",      # namespace de la clase Strings
  "resourceBase": "Proyecto.Properties.Strings",   # opcional (RootNamespace + .Properties.Strings)
  "strings": {"Clave": ["English", "Español"]},
  "replace": [{"file": "Relativo.cs", "old": "...", "new": "...", "count": 1}]
}
Antes de escribir nada verifica que cada "old" aparezca exactamente "count" veces y que
toda clave usada (Strings.X) esté definida.
"""
import json, os, sys, re
from xml.sax.saxutils import escape, unescape

HEADER = '''<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
'''

def load_resx(path):
    if not os.path.exists(path):
        return {}
    text = open(path, encoding="utf-8-sig").read()
    return {m.group(1): unescape(m.group(2)) for m in
            re.finditer(r'<data name="([^"]+)" xml:space="preserve">\s*<value>(.*?)</value>', text, re.S)}

def write_resx(path, items):
    out = [HEADER]
    for k in sorted(items):
        out.append(f'  <data name="{k}" xml:space="preserve"><value>{escape(items[k])}</value></data>\n')
    out.append("</root>\n")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write("".join(out))

def write_accessor(props_dir, namespace, resource_base, en):
    lines = [
        "// <auto-generated>",
        "// Generado por tools/i18n.py a partir de Strings.resx. No editar a mano: regenerar con",
        "//   python tools/i18n.py --regen <carpeta del proyecto>",
        "// </auto-generated>",
        "#nullable enable",
        "using System.Globalization;",
        "using System.Resources;",
        "",
        f"namespace {namespace};",
        "",
        "/// <summary>Textos de la interfaz en el idioma actual (CurrentUICulture), con inglés como respaldo.</summary>",
        "public static class Strings",
        "{",
        "    private static ResourceManager? _resourceManager;",
        "",
        f'    public static ResourceManager ResourceManager => _resourceManager ??= new ResourceManager("{resource_base}", typeof(Strings).Assembly);',
        "",
        "    /// <summary>Idioma forzado (null = el de la interfaz actual).</summary>",
        "    public static CultureInfo? Culture { get; set; }",
        "",
    ]
    for k in sorted(en):
        summary = escape(en[k].replace("\n", " "))
        lines.append(f"    /// <summary>{summary}</summary>")
        lines.append(f'    public static string {k} => ResourceManager.GetString("{k}", Culture) ?? "{k}";')
        lines.append("")
    lines.append("}")
    open(os.path.join(props_dir, "Strings.cs"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

def project_info(root):
    csproj = next(os.path.join(root, f) for f in os.listdir(root) if f.endswith(".csproj"))
    c = open(csproj, encoding="utf-8-sig").read()
    m = re.search(r"<RootNamespace>([^<]+)</RootNamespace>", c)
    root_ns = m.group(1) if m else os.path.splitext(os.path.basename(csproj))[0]
    return csproj, root_ns

def regen(root):
    _, root_ns = project_info(root)
    props = os.path.join(root, "Properties")
    write_accessor(props, f"{root_ns}.Properties", f"{root_ns}.Properties.Strings", load_resx(os.path.join(props, "Strings.resx")))
    print(f"Strings.cs regenerado en {props}")

def main():
    if sys.argv[1] == "--regen":
        regen(sys.argv[2]); return
    spec = json.load(open(sys.argv[1], encoding="utf-8"))
    dry = "--dry" in sys.argv
    root = spec["root"]
    csproj, root_ns = project_info(root)
    namespace = spec.get("namespace", f"{root_ns}.Properties")
    resource_base = spec.get("resourceBase", f"{root_ns}.Properties.Strings")
    props = os.path.join(root, "Properties")

    pending, errors = {}, []
    for r in spec.get("replace", []):
        path = os.path.join(root, r["file"])
        text = pending.get(path) or open(path, encoding="utf-8-sig").read()
        n = text.count(r["old"])
        if n != r.get("count", 1):
            errors.append(f'{r["file"]}: esperaba {r.get("count", 1)} y encontré {n}: {r["old"][:90]!r}')
            continue
        pending[path] = text.replace(r["old"], r["new"])
    if errors:
        print("NO SE APLICÓ NADA. Errores:")
        for e in errors: print("  - " + e)
        sys.exit(1)

    en = load_resx(os.path.join(props, "Strings.resx"))
    es = load_resx(os.path.join(props, "Strings.es.resx"))
    known = set(en) | set(spec.get("strings", {}))
    used = set()
    for t in pending.values():
        used |= set(re.findall(r'(?<![A-Za-z0-9_.])Strings\.([A-Za-z][A-Za-z0-9_]*)', t))
    missing = sorted(k for k in used if k not in known and k not in ("ResourceManager", "Culture"))
    if missing:
        print("NO SE APLICÓ NADA. Claves usadas sin definir: " + ", ".join(missing))
        sys.exit(1)
    if dry:
        print(f"OK (simulación): {len(spec.get('replace', []))} reemplazos, {len(spec.get('strings', {}))} textos"); return

    for path, text in pending.items():
        open(path, "w", encoding="utf-8").write(text)
    for k, (e, s) in spec.get("strings", {}).items():
        en[k], es[k] = e, s
    write_resx(os.path.join(props, "Strings.resx"), en)
    write_resx(os.path.join(props, "Strings.es.resx"), es)
    write_accessor(props, namespace, resource_base, en)
    print(f"OK: {len(spec.get('replace', []))} reemplazos en {len(pending)} archivos, {len(spec.get('strings', {}))} textos ({len(en)} en total)")

if __name__ == "__main__":
    main()
